'use client';

import { SOURCES, type Source } from '@/lib/sources';
import Link from 'next/link';
import { useEffect, useState } from 'react';
import { profileOf } from '@/lib/canvas/profile';

// ?lesson=<id>: that lesson's sources (its profile, lib/canvas/profile.ts); none: the blue catfish lesson's
export default function SourcesPage() {
  const [lesson, setLesson] = useState('');
  const [sources, setSources] = useState<Source[]>(SOURCES);
  // Pictures from outside (free to use with credit): who made each one, from the lesson's slides
  const [pictures, setPictures] = useState<{ credit: string; url?: string; src: string }[]>([]);
  useEffect(() => {
    const id = new URLSearchParams(window.location.search).get('lesson') ?? '';
    if (!/^[a-z0-9][a-z0-9-]{0,60}$/.test(id)) return;
    setLesson(id);
    fetch(`/api/deck?lesson=${encodeURIComponent(id)}`).then((r) => r.json()).then((d) => {
      if (!d?.deck) return;
      setSources(profileOf(d.deck).sources);
      const seen = new Map<string, { credit: string; url?: string; src: string }>();
      const look = (els: { type: string; src?: string; credit?: string; creditUrl?: string }[] = []) => { for (const e of els) if (e.type === 'image' && e.credit && e.src && !seen.has(e.src)) seen.set(e.src, { credit: e.credit, url: e.creditUrl, src: e.src }); };
      for (const s of d.deck.slides ?? []) { look(s.elements); look(s.helper?.elements); }
      for (const q of d.deck.bank?.questions ?? []) look(q.slide?.elements);
      setPictures([...seen.values()]);
    }).catch(() => { /* the default list */ });
  }, []);
  return (
    <div className="min-h-screen bg-gradient-to-br from-mist-400 via-mist-50 to-mist-400 p-8">
      <div className="max-w-3xl mx-auto">
        {/* was /presentationv2: the canvas page is the main lesson now */}
        <Link href={lesson ? `/presentation?lesson=${lesson}` : '/presentation'} className="text-blue-600 hover:underline text-sm">
          ← Back to the lesson
        </Link>

        <h1 className="text-4xl font-bold text-black mt-6 mb-2">Sources</h1>
        <p className="text-blue-700 mb-10">
          Everything in this lesson is drawn from these publicly available resources.
        </p>

        <div className="space-y-4">
          {sources.map((s, i) => (
            <a
              key={i}
              href={s.url}
              target="_blank"
              rel="noopener noreferrer"
              className="block bg-white/60 hover:bg-white rounded-2xl border border-blue-200 hover:border-blue-400 p-5 transition-colors"
            >
              <div className="font-semibold text-blue-900">{s.title}</div>
              <div className="text-sm text-slate-600 mt-1">{s.org}</div>
            </a>
          ))}
        </div>

        {pictures.length > 0 && (
          <>
            <h2 className="text-2xl font-bold text-black mt-12 mb-2">Pictures</h2>
            <p className="text-blue-700 mb-5">These pictures are free to use with credit. Thank you to the people who made them.</p>
            <ul className="space-y-2" data-picture-credits>
              {pictures.map((p) => (
                <li key={p.src} className="flex items-center gap-3 bg-white/60 rounded-xl border border-blue-200 p-2">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={p.src} alt="" className="w-14 h-14 rounded-lg object-cover shrink-0" loading="lazy" />
                  {p.url
                    ? <a href={p.url} target="_blank" rel="noopener noreferrer" className="text-sm text-blue-900 hover:underline">{p.credit}</a>
                    : <span className="text-sm text-blue-900">{p.credit}</span>}
                </li>
              ))}
            </ul>
          </>
        )}

        <p className="text-slate-500 text-sm mt-10">
          Lesson content is generated by AI from these sources. Images and narration are
          produced automatically and may contain errors — always check the originals.
        </p>
      </div>
    </div>
  );
}
