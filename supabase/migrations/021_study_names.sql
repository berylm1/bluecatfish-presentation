-- Each study's groups kept even (the group with fewer people, test runs aside), under a lock
create or replace function public.adaptive_assign(p_id uuid) returns text language plpgsql set search_path = public as $$
declare current_group text; n_static int; n_adaptive int; picked text;
begin
  perform pg_advisory_xact_lock(hashtext('adaptive_assign'));
  select study_group into current_group from public.adaptive_participants where id = p_id;
  if not found then return null; end if;
  if current_group is not null then return current_group; end if;
  select count(*) filter (where study_group = 'static'), count(*) filter (where study_group = 'adaptive')
    into n_static, n_adaptive from public.adaptive_participants where not is_test;
  if n_static < n_adaptive then picked := 'static';
  elsif n_adaptive < n_static then picked := 'adaptive';
  elsif random() < 0.5 then picked := 'static';
  else picked := 'adaptive';
  end if;
  update public.adaptive_participants set study_group = picked, updated_at = now() where id = p_id;
  return picked;
end $$;

create or replace function public.classmates_assign(p_id uuid) returns text language plpgsql set search_path = public as $$
declare current_group text; n_with int; n_without int; picked text;
begin
  perform pg_advisory_xact_lock(hashtext('classmates_assign'));
  select study_group into current_group from public.classmates_participants where id = p_id;
  if not found then return null; end if;
  if current_group is not null then return current_group; end if;
  select count(*) filter (where study_group = 'classmates'), count(*) filter (where study_group = 'no_classmates')
    into n_with, n_without from public.classmates_participants where not is_test;
  if n_with < n_without then picked := 'classmates';
  elsif n_without < n_with then picked := 'no_classmates';
  elsif random() < 0.5 then picked := 'classmates';
  else picked := 'no_classmates';
  end if;
  update public.classmates_participants set study_group = picked, updated_at = now() where id = p_id;
  return picked;
end $$;

revoke execute on function public.adaptive_assign(uuid) from public, anon, authenticated;
revoke execute on function public.classmates_assign(uuid) from public, anon, authenticated;
grant execute on function public.adaptive_assign(uuid) to service_role;
grant execute on function public.classmates_assign(uuid) to service_role;
