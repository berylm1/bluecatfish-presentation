-- Migration 019: study 2, static vs adaptive (/study2; lib/study/content.ts STUDY2)
-- Its own table, the same shape as study_participants after 017 and 018: one row per person,
-- in the group 'static' (the professor reads the slides; nothing responds) or 'adaptive'
-- (the lesson as it is, with the classmates). Our server only (RLS on, no policies).
-- study2_assign: the group with fewer people (test runs aside), under a lock. Safe to rerun.
create table if not exists public.study2_participants (
  id                   uuid primary key default gen_random_uuid(),
  participant_no       bigint generated by default as identity,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  is_test              boolean not null default false,
  step                 text not null default 'consent',
  study_group          text check (study_group in ('static', 'adaptive')),
  consent_at           timestamptz,
  demographics         jsonb,
  seen_before_browser  boolean,
  device               text,
  screen               text,
  sound_ok             boolean,
  mic_ok               boolean,
  camera_ok            boolean,
  lesson_version       text,
  lesson_session       text,
  lesson_started_at    timestamptz,
  lesson_finished_at   timestamptz,
  pre_quiz             jsonb,
  post_quiz            jsonb,
  survey               jsonb,
  pre_score            int,
  post_score           int,
  post_same_score      int,
  finished_at          timestamptz,
  interview_notes      text
);
create index if not exists study2_participants_group on public.study2_participants (study_group) where not is_test;
alter table public.study2_participants enable row level security;

create or replace function public.study2_assign(p_id uuid) returns text language plpgsql set search_path = public as $$
declare
  current_group text;
  n_static int;
  n_adaptive int;
  picked text;
begin
  perform pg_advisory_xact_lock(hashtext('study2_assign'));
  select study_group into current_group from public.study2_participants where id = p_id;
  if not found then return null; end if;
  if current_group is not null then return current_group; end if;
  select count(*) filter (where study_group = 'static'), count(*) filter (where study_group = 'adaptive')
    into n_static, n_adaptive from public.study2_participants where not is_test;
  if n_static < n_adaptive then picked := 'static';
  elsif n_adaptive < n_static then picked := 'adaptive';
  elsif random() < 0.5 then picked := 'static';
  else picked := 'adaptive';
  end if;
  update public.study2_participants set study_group = picked, updated_at = now() where id = p_id;
  return picked;
end $$;
revoke execute on function public.study2_assign(uuid) from public, anon, authenticated;
grant execute on function public.study2_assign(uuid) to service_role;
